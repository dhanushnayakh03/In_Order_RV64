

.section .text
.globl _start

_start:

   
    la      x10, operands

    ld      x1,  0(x10) #10 
    ld      x2,  8(x10)
    ld      x3,  16(x10)
    ld      x4,  24(x10)
    ld      x5,  32(x10)
    ld      x6,  40(x10)
    ld      x7,  48(x10)
    ld      x8,  56(x10) #80 


    # ------------------------------------------------------------------------
    # Block A: True data dependencies (RAW)
    # ------------------------------------------------------------------------

    add     x12, x1, x2          # x12 = x1 + x2  x12 = 30 
    add     x13, x12, x3         # RAW: depends on x12 x13 = 30 + 30 = 60
    sub     x14, x13, x4         # RAW: depends on x13  x14 = 60 - 40 = 20


    # ------------------------------------------------------------------------
    # Block B: Independent arithmetic instructions
    # ------------------------------------------------------------------------

    add     x15, x1, x3          # Independent  # x15 = 10 + 30 = 40 
    sub     x16, x2, x4          # Independent  # x16 = 20 - 40 = -20
    add     x17, x5, x6          # Independent  # x17 = 50 + 60 = 110
    sub     x18, x7, x8          # Independent  # x18 = 70 - 80 = -10


    # ------------------------------------------------------------------------
    # Block C: WAR dependency (Write After Read)
    # ------------------------------------------------------------------------

    add     x19, x1, x2          # Reads old x1     # x19 = 10 + 20 = 30
    sub     x1, x3, x4           # Overwrites x1    # x1 = 30 - 40 = -10 
    add     x20, x1, x5          # Reads new x1     # x20 = -10 + 50 = 40 


    # ------------------------------------------------------------------------
    # Block D: WAW dependency (Write After Write)
    # ------------------------------------------------------------------------

    add     x21, x2, x3          # First write to x21  # x21 = 20 + 30 = 50
    sub     x21, x4, x5          # Second write to x21 # x21 = 40 - 50 = -10


    # ------------------------------------------------------------------------
    # Finished
    # ------------------------------------------------------------------------

    wfi


# ============================================================================
# Data Section: Initial operands at address 0x1000
# ============================================================================

.section .data
.align 3

operands:
    .dword  10, 20, 30, 40
    .dword  50, 60, 70, 80
